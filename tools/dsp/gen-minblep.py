#!/usr/bin/env python3
"""Generate src/engine/dsp/minblep_tables.c: the VCO's band-limiting kernels (VS-30, ADR-010).

    python3 tools/dsp/gen-minblep.py              rewrite minblep_tables.c
    python3 tools/dsp/gen-minblep.py --check      exit 1 if the committed file differs
    python3 tools/dsp/gen-minblep.py -o PATH      write elsewhere (the CI byte-equality test)

ADR-010's specification, step by step:
1. A windowed sinc at an oversampling factor of 64, spanning 32 output samples (2,048 taps + 1),
   cutoff 0.875 x Nyquist (21.0 kHz at 48 kHz), 4-term Blackman-Harris window; unit DC gain.
2. Minimum phase by the real-cepstrum method, FFT size 65,536 at the oversampled rate (>= 16,384).
3. The running sum, normalised to end at exactly 1.0, is the minBLEP. Minus the unit step it is
   the minBLEP RESIDUAL. Its running integral (in output samples) minus the unit ramp is the
   minBLAMP residual.
4. Each residual as float[33][65] (output sample k = 0..32 by phase j = 0..64, value at
   x = k + j/64 samples after the discontinuity; the guard row and column make linear
   interpolation need no bounds test).

A minimum-phase kernel lags the step by its centroid D (about two samples here), so the band-limited
ramp ends up D samples late: the minBLAMP residual does not decay to 0 but to -D. The table stores
the residual MINUS that final value, so it decays to 0 inside the 32-sample ring, and the final
value is a separate constant (`sx_minblamp_tail`); vco.c keeps the tail as a per-output offset
proportional to the current slope (see vco.c). The sum is exactly ADR-010's minBLAMP residual.

Values are rounded to float32 and printed with 9 significant digits (exact for float32), so the file
is byte-identical wherever numpy's FFT agrees to well under one float32 unit. The header carries
the parameters and the SHA-256 of the numbers (the float32 bytes, little-endian, minBLEP then
minBLAMP then the tail).
"""

from __future__ import annotations

import argparse
import hashlib
import struct
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src" / "engine" / "dsp" / "minblep_tables.c"

OVERSAMPLE = 64
SPAN = 32  # output samples
CUTOFF = 0.875  # x Nyquist
FFT_N = 65536
TAPS = SPAN * OVERSAMPLE  # 2048 (+1 for symmetry)


def blackman_harris(n: int) -> np.ndarray:
    a0, a1, a2, a3 = 0.35875, 0.48829, 0.14128, 0.01168
    k = np.arange(n) / (n - 1)
    return a0 - a1 * np.cos(2 * np.pi * k) + a2 * np.cos(4 * np.pi * k) - a3 * np.cos(6 * np.pi * k)


def kernels() -> tuple[np.ndarray, np.ndarray, float]:
    n = TAPS + 1
    t = (np.arange(n) - TAPS / 2) / OVERSAMPLE  # output samples
    fc = CUTOFF * 0.5  # cycles per output sample
    h = 2 * fc * np.sinc(2 * fc * t) * blackman_harris(n)
    h /= h.sum()

    # Minimum phase: fold the real cepstrum of log|H|.
    spec = np.fft.fft(h, FFT_N)
    logmag = np.log(np.maximum(np.abs(spec), 1e-12))
    cep = np.fft.ifft(logmag).real
    fold = np.zeros(FFT_N)
    fold[0] = cep[0]
    fold[1 : FFT_N // 2] = 2 * cep[1 : FFT_N // 2]
    fold[FFT_N // 2] = cep[FFT_N // 2]
    hmin = np.fft.ifft(np.exp(np.fft.fft(fold))).real[:n]

    step = np.cumsum(hmin)
    step /= step[-1]  # ends at exactly 1.0
    ramp = np.cumsum(step) / OVERSAMPLE  # integral in output samples
    x = np.arange(n) / OVERSAMPLE

    rows, cols = SPAN + 1, OVERSAMPLE + 1
    blep = np.zeros((rows, cols))
    blamp = np.zeros((rows, cols))
    tail = float(ramp[-1] - x[-1])  # the final value of the minBLAMP residual (-D)
    for k in range(rows):
        for j in range(cols):
            m = k * OVERSAMPLE + j
            if m < n:
                blep[k, j] = step[m] - 1.0
                blamp[k, j] = (ramp[m] - x[m]) - tail
            # past the kernel: the step is complete and the ramp is at its final offset (0)
    return blep.astype(np.float32), blamp.astype(np.float32), tail


def fmt(v: np.float32) -> str:
    s = f"{float(v):.9g}"
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def render() -> str:
    blep, blamp, tail = kernels()
    tail32 = np.float32(tail)
    raw = blep.astype("<f4").tobytes() + blamp.astype("<f4").tobytes()
    raw += struct.pack("<f", float(tail32))
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "/* minblep_tables.c: GENERATED by tools/dsp/gen-minblep.py (VS-30, ADR-010). Do not edit:",
        " * regenerate, and treat any change as a golden-render re-bless.",
        " *",
        f" * Blackman-Harris (4-term) windowed sinc, oversampling {OVERSAMPLE}, span {SPAN} output",
        f" * samples, cutoff {CUTOFF} x Nyquist, minimum phase by real cepstrum (FFT {FFT_N}).",
        " * sx_minblep[k][j]:  minBLEP minus the unit step, at x = k + j/64 samples.",
        " * sx_minblamp[k][j]: minBLAMP minus the unit ramp, minus its final value sx_minblamp_tail.",
        f" * SHA-256 of the float32 values: {digest}",
        " */",
        '#include "minblep.h"',
        "",
        "/* clang-format off */",
        f"const float sx_minblamp_tail = {fmt(tail32)};",
        "",
    ]
    for name, tab in (("sx_minblep", blep), ("sx_minblamp", blamp)):
        lines.append(f"const float {name}[SX_BLEP_ROWS][SX_BLEP_COLS] = {{")
        for k in range(tab.shape[0]):
            vals = [fmt(v) for v in tab[k]]
            lines.append("    {")
            for i in range(0, len(vals), 6):
                lines.append("        " + ", ".join(vals[i : i + 6]) + ",")
            lines.append("    },")
        lines.append("};")
        lines.append("")
    lines.append("/* clang-format on */")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("-o", "--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} differs from a fresh generation", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
