#!/usr/bin/env python3
"""Generate src/engine/machine/cycles_table.c from tools/cycles/cycles-716.tsv (VS-02, MACH-5).

    python3 tools/cycles/gen-cycles-c.py            rewrite cycles_table.c
    python3 tools/cycles/gen-cycles-c.py --check    exit 1 if cycles_table.c is out of date

The TSV is the single source of the instruction timings (SP-S4B). This script turns it into a
256-entry C table indexed by primary opcode byte, in nanoseconds, plus the table's STATUS line,
so the engine charges exactly what tools/cycle-calc.py computes. The status (ESTIMATE until
a 7/16 source is cited) is carried into the C file and from there into the engine, so no
consumer can lose the label.

Each row also gets a `kind` that tells the engine where its per-n count and its branch
condition come from (the same model as cycle-calc.py: one execution costs
(taken ? taken_ns : base_ns) + per_n_ns * n):

    SX_CK_PLAIN   no per-n term, not a conditional branch
    SX_CK_BT      branch taken when (cc & R1) != 0   (BTCR BTC BTBS BTFS)
    SX_CK_BF      branch taken when (cc & R1) == 0   (BFCR BFC BFBS BFFS)
    SX_CK_N_R2    n = the R2 field                   (SRLS SLLS: short-form shift count)
    SX_CK_N_SH16  n = operand & 0xF                  (SRHL SLHL SRHA SLHA)
    SX_CK_N_SH32  n = operand & 0x1F                 (RRL RLL SRL SLL SRA SLA)
    SX_CK_N_REGS  n = 16 - R1                        (STM LM: registers moved)

Rows with a per-n cost the engine cannot see at decode (the block I/O byte counts of WB RB
WBR RBR, outside subset m74-portable-1) are charged base only, and say so in a comment.
Opcodes not in the table (not in the 716 class) cost 1 cycle: the CPU traps them.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TSV = ROOT / "tools" / "cycles" / "cycles-716.tsv"
OUT = ROOT / "src" / "engine" / "machine" / "cycles_table.c"

BT = {"BTCR", "BTC", "BTBS", "BTFS"}
BF = {"BFCR", "BFC", "BFBS", "BFFS"}
N_R2 = {"SRLS", "SLLS"}
N_SH16 = {"SRHL", "SLHL", "SRHA", "SLHA"}
N_SH32 = {"RRL", "RLL", "SRL", "SLL", "SRA", "SLA"}
N_REGS = {"STM", "LM"}
N_UNSEEN = {"WB", "RB", "WBR", "RBR"}


def rows() -> tuple[str, list[tuple[str, int, int, int, int, str]]]:
    status, out, seen_hdr = "UNKNOWN", [], False
    for line in TSV.read_text().splitlines():
        if line.startswith("#"):
            m = re.match(r"#\s*STATUS:\s*(\S+)", line)
            if m:
                status = m.group(1)
            continue
        if not line.strip():
            continue
        cols = line.split("\t")
        if not seen_hdr:
            seen_hdr = True
            continue
        mn, op, _form, base, per_n, taken = cols[:6]
        out.append((mn, int(op, 16), int(base), int(per_n), int(taken), cols[6]))
    return status, out


def kind(mn: str, per_n: int, taken: int) -> str:
    if mn in BT:
        return "SX_CK_BT"
    if mn in BF:
        return "SX_CK_BF"
    if taken:
        raise ValueError(f"{mn}: taken time but no branch rule")
    for names, k in ((N_R2, "SX_CK_N_R2"), (N_SH16, "SX_CK_N_SH16"), (N_SH32, "SX_CK_N_SH32"),
                     (N_REGS, "SX_CK_N_REGS")):  # fmt: skip
        if mn in names:
            return k
    if per_n and mn not in N_UNSEEN:
        raise ValueError(f"{mn}: per-n cost but no rule for n")
    return "SX_CK_PLAIN"


def render() -> str:
    status, table = rows()
    by_op: dict[int, tuple[str, int, int, int, int, str]] = {}
    for r in table:
        if r[1] in by_op:
            raise ValueError(f"opcode {r[1]:02X} twice")
        by_op[r[1]] = r
    lines = [
        "/* cycles_table.c: GENERATED by tools/cycles/gen-cycles-c.py from tools/cycles/cycles-716.tsv.",
        " * Edit the TSV (or the script), never this file; tests/engine/test_cycles_table.py checks",
        " * the two agree.",
        " *",
        f" * STATUS: {status}. These are Interdata Model 74 times used as a proxy for the 7/16",
        " * (SP-S4B, docs/qa/results/M1/S4.md); MACH-5 may not cite them until a 7/16 source is",
        " * read. Times in ns: base (branch not taken), per unit of n, branch taken.",
        " */",
        '#include "cycles.h"',
        "",
        f'const char sx_cycles_status[] = "{status}";',
        f"const unsigned sx_cycles_rows = {len(table)}u;",
        "",
        "/* clang-format off */",
        "const sx_cyc_row sx_cyc_table[256] = {",
    ]
    for op in range(256):
        if op not in by_op:
            continue
        mn, _, base, per_n, taken, conf = by_op[op]
        note = " (n not modelled: block I/O)" if mn in N_UNSEEN and per_n else ""
        lines.append(
            f"    [0x{op:02X}] = {{{base}u, {per_n}u, {taken}u, {kind(mn, per_n, taken)}}},"
            f" /* {mn} {conf}{note} */"
        )
    lines += ["};", "/* clang-format on */", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/cycles/gen-cycles-c.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
