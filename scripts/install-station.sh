#!/usr/bin/env bash
# install-station.sh: install the station (rigd + page server + Chromium kiosk window) on a
# Debian box (systemd) or a Mac (launchd). KP-11, ADR-006; ported from the Model 4 kiosk's
# deploy/install.sh.
#
#   scripts/install-station.sh                     DRY RUN (the default): say what would change
#   sudo scripts/install-station.sh --apply        do it, on this machine
#   scripts/install-station.sh --apply --root DIR  stage the whole install under DIR (no root
#                                                  needed; nothing outside DIR is touched)
#   scripts/install-station.sh --print-paths       every path it installs, one per line
#
# Options: --platform linux|macos (default: this machine)  --dest DIR (/opt/seastones)
#          --data DIR (/data on Linux, /Users/Shared/Seastones/data on macOS)
#          --python PATH  --kiosk-user NAME  --no-packages  --allow-missing-build
#
# Idempotent: a second run changes nothing and says "0 change(s)". It never overwrites the
# station's own state in <data> (staff settings, saved presets, logs, counters, the PIN), and
# it contains no secrets: the staff PIN is set on the station with scripts/staff-pin.py.
# Before installing, build the production profile: `make host-production`.
#
# Linux start path (one path for the display, Model 4 lesson):
#   BIOS restore-on-AC -> agetty autologin (kiosk) -> startx -> .xinitrc loop -> kiosk.sh
#   systemd: seastones-station.target = rigd (Restart=always, WatchdogSec=5) + web + timers
# macOS: LaunchAgents in the kiosk user's login session, each under deploy/supervise.py
#   (restart, rigd's heartbeat watchdog, log rotation); needs automatic login.
set -euo pipefail

PROG=install-station
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck disable=SC1091  # sourced by path; linted on its own
. "$REPO/scripts/station-lib.sh"

PLATFORM=""
DEST=""
DATA=""
PY=""
KIOSK_USER=""
SKIP_PACKAGES=0
ALLOW_MISSING_BUILD=0
SVC_USER=seastones
MARK="Generated by scripts/install-station.sh"

usage() { sed -n '2,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --apply) APPLY=1; shift ;;
    --dry-run) APPLY=0; shift ;;
    --root) ROOT="${2:?--root needs a directory}"; shift 2 ;;
    --platform) PLATFORM="${2:-}"; shift 2 ;;
    --dest) DEST="${2:-}"; shift 2 ;;
    --data) DATA="${2:-}"; shift 2 ;;
    --python) PY="${2:-}"; shift 2 ;;
    --kiosk-user) KIOSK_USER="${2:-}"; shift 2 ;;
    --no-packages) SKIP_PACKAGES=1; shift ;;
    --allow-missing-build) ALLOW_MISSING_BUILD=1; shift ;;
    --print-paths) PRINT_PATHS=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "$PROG: unknown argument $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [ -z "$PLATFORM" ]; then
  case "$(uname -s)" in Darwin) PLATFORM=macos ;; Linux) PLATFORM=linux ;; *) die "unknown platform" ;; esac
fi
case "$PLATFORM" in
  linux)
    DEST="${DEST:-/opt/seastones}"; DATA="${DATA:-/data}"; PY="${PY:-/usr/bin/python3}"
    KIOSK_USER="${KIOSK_USER:-kiosk}"; LIBEXT=so ;;
  macos)
    DEST="${DEST:-/opt/seastones}"; DATA="${DATA:-/Users/Shared/Seastones/data}"
    PY="${PY:-$(command -v python3 || echo /usr/bin/python3)}"
    KIOSK_USER="${KIOSK_USER:-${SUDO_USER:-$(id -un)}}"; LIBEXT=dylib ;;
  *) die "--platform must be linux or macos" ;;
esac
if [ -n "$ROOT" ]; then
  [ "$APPLY" = 0 ] || mkdir -p "$ROOT"
  if [ -d "$ROOT" ]; then ROOT="$(cd "$ROOT" && pwd)"; fi
fi
if live && [ "$(id -u)" -ne 0 ]; then
  die "--apply changes this machine and needs root (sudo), or use --root DIR to stage it"
fi

CONF="$REPO/deploy/station.conf"
LOG_KEEP="$(conf_get "$CONF" LOG_ROTATE_COUNT 5)"
LOG_KB="$(conf_get "$CONF" LOG_ROTATE_SIZE_KB 2048)"
RESET_TIME="$(conf_get "$CONF" RESET_TIME 03:30)"
RESET_DELAY="$(conf_get "$CONF" RESET_RANDOM_DELAY_S 300)"
WD_SEC="$(conf_get "$CONF" RIGD_WATCHDOG_SEC 5)"
BUDGET="$(conf_get "$CONF" BOOT_BUDGET_S 90)"
case "$RESET_TIME" in [0-2][0-9]:[0-5][0-9]) ;; *) die "station.conf RESET_TIME must be HH:MM" ;; esac

say "the 1974 Seastones Rig: $PLATFORM station -> $DEST, state in $DATA${ROOT:+ (staged under $ROOT)}"
[ "$APPLY" = 1 ] || note "dry run: nothing will be changed"

# --- 0. preflight --------------------------------------------------------------------------
LIB="build/prod/host/libsxhost.$LIBEXT"
PROGRAM_FILES="build/prod/program/rig.img.json build/prod/program/rig.lst.json build/prod/program/rig8.img.json build/prod/program/rig8.lst.json"
missing=""
for f in $LIB $PROGRAM_FILES THIRD-PARTY-NOTICES; do
  [ -f "$REPO/$f" ] || missing="$missing $f"
done
if [ -n "$missing" ]; then
  if [ "$APPLY" = 1 ] && [ "$ALLOW_MISSING_BUILD" = 0 ] && [ "$PRINT_PATHS" = 0 ]; then
    die "not built:$missing. Run: make host-production notices (on the $PLATFORM station itself)"
  fi
  [ "$PRINT_PATHS" = 1 ] || warn "not built here:$missing (make host-production notices); skipped"
fi

# --- 1. packages and accounts (Linux, live only) ---------------------------------------------
if [ "$PLATFORM" = linux ]; then
  say "packages and accounts"
  if [ "$SKIP_PACKAGES" = 0 ]; then
    # ALSA only: no PipeWire or PulseAudio on the image (ADR-006). No desktop, no SSH server.
    do_run apt-get install -y --no-install-recommends python3 python3-websockets python3-cffi \
      xserver-xorg xinit x11-xserver-utils xinput unclutter openbox chromium alsa-utils \
      nftables logrotate
  fi
  if live && ! id "$SVC_USER" >/dev/null 2>&1; then
    do_run useradd --system --no-create-home --user-group --groups audio "$SVC_USER"
  elif ! live; then
    note "would make sure the users exist: $SVC_USER (system, audio) and $KIOSK_USER (the display)"
  fi
  if live && ! id "$KIOSK_USER" >/dev/null 2>&1; then
    do_run useradd -m -s /bin/bash -G video,input,"$SVC_USER" "$KIOSK_USER"
    do_run passwd -l "$KIOSK_USER"
  fi
fi

# --- 2. the application (read-only at run time) ------------------------------------------------
say "application -> $DEST"
MANIFEST="$DEST/.install-manifest"
MANIFEST_NEW="$(mktemp "${TMPDIR:-/tmp}/sx-manifest.XXXXXX")"
trap 'rm -f "$MANIFEST_NEW"' EXIT
OWN="root:$( [ "$PLATFORM" = macos ] && echo wheel || echo root )"
do_dir "$DEST" 0755 "$OWN"

mode_for() {
  case "$1" in
    *.sh|deploy/supervise.py|deploy/watchdog.py|deploy/playable.py|scripts/staff-pin.py) echo 0755 ;;
    *) echo 0644 ;;
  esac
}

app_files() {
  (cd "$REPO" && find src/rigd src/web src/content src/toolchain -type f \
      \( -name '*.py' -o -name '*.json' -o -name '*.html' -o -name '*.js' -o -name '*.css' \
         -o -name '*.woff2' -o -name '*.svg' -o -name '*.png' -o -name '*.txt' \) \
      -not -path '*/__pycache__/*' | LC_ALL=C sort)
  for f in deploy/kiosk.sh deploy/restart-browser.sh deploy/reset.sh deploy/supervise.py \
           deploy/watchdog.py deploy/playable.py deploy/boot-wait.html deploy/station.conf \
           scripts/staff-pin.py docs/OPERATIONS.md docs/ARCHITECTURE.md THIRD-PARTY-NOTICES \
           $LIB $PROGRAM_FILES; do
    [ -f "$REPO/$f" ] && echo "$f"
  done
  (cd "$REPO" && find licenses -type f | LC_ALL=C sort)
}
for f in $(app_files); do
  do_file "$REPO/$f" "$DEST/$f" "$(mode_for "$f")" "$OWN"
done
# the baked content: what the station shows with no content stick (CT-08's last known good)
for f in $(cd "$REPO" && find content -type f -not -name '.DS_Store' | LC_ALL=C sort); do
  do_file "$REPO/$f" "$DEST/content-baked/${f#content/}" 0644 "$OWN"
done
commit="$(cd "$REPO" && git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
dirty=""
if [ -n "$(cd "$REPO" && git status --porcelain --untracked-files=no 2>/dev/null)" ]; then dirty=" (with uncommitted changes)"; fi
do_text "$DEST/VERSION" 0644 "$OWN" <<EOF
commit: $commit$dirty
simh.pin: $(grep -v '^#' "$REPO/deploy/simh.pin" 2>/dev/null | head -1)
platform: $PLATFORM
EOF

# --- 3. the station's own state (never overwritten) -------------------------------------------
say "state -> $DATA"
DOWN="$SVC_USER:$SVC_USER"
[ "$PLATFORM" = macos ] && DOWN="$KIOSK_USER:staff"
do_dir "$DATA" 0755 "$DOWN"
for d in log presets content counters; do do_dir "$DATA/$d" 0775 "$DOWN"; done
do_dir "$DATA/chrome" 0700 "$KIOSK_USER"
[ "$PLATFORM" = macos ] && do_dir "$DATA/run" 0755 "$DOWN"
if [ ! -e "$(R "$DATA/content/kiosk.conf")" ]; then
  # first install: the content set starts as the baked copy (the stick replaces it, CT-08)
  NO_MANIFEST=1
  for f in $(cd "$REPO" && find content -type f -not -name '.DS_Store' | LC_ALL=C sort); do
    do_file "$REPO/$f" "$DATA/$f" 0644 "$DOWN"
  done
  # shellcheck disable=SC2034  # read by do_file in station-lib.sh
  NO_MANIFEST=0
fi
if [ ! -e "$(R "$DATA/staff-pin")" ] && [ "$PRINT_PATHS" = 0 ]; then
  note "no staff PIN yet: until one is set the staff screen stays closed. Set it on the station:"
  note "  sudo $PY $DEST/scripts/staff-pin.py $DATA/staff-pin"
fi

# --- 4. supervision -------------------------------------------------------------------------
sub() {  # template -> stdout, with the @NAMES@ filled
  sed -e "s|@PYTHON@|$PY|g" -e "s|@DEST@|$DEST|g" -e "s|@DATA@|$DATA|g" \
      -e "s|@LOG_MAX_KB@|$LOG_KB|g" -e "s|@LOG_KEEP@|$LOG_KEEP|g" \
      -e "s|@RIGD_WATCHDOG_SEC@|$WD_SEC|g" -e "s|@BOOT_BUDGET_S@|$BUDGET|g" "$1"
}

if [ "$PLATFORM" = linux ]; then
  say "systemd units, logs, watchdogs, firewall"
  U=/etc/systemd/system
  for u in seastones-rigd.service seastones-web.service seastones-playable.service \
           seastones-watchdog.service seastones-watchdog.timer seastones-reset.service \
           seastones-reset.timer seastones-station.target; do
    sed -e "s|/opt/seastones|$DEST|g" -e "s|/data|$DATA|g" \
        -e "s|^OnCalendar=.*|OnCalendar=*-*-* $RESET_TIME:00|" \
        -e "s|^RandomizedDelaySec=.*|RandomizedDelaySec=$RESET_DELAY|" \
        -e "s|^WatchdogSec=.*|WatchdogSec=$WD_SEC|" \
        -e "s|--budget 90|--budget $BUDGET|" "$REPO/deploy/systemd/$u" \
      | do_text "$U/$u" 0644 root:root
  done
  do_text /etc/systemd/journald.conf.d/10-seastones.conf 0644 root:root <<EOF
# $MARK: journald in memory, capped (no flash wear, nothing to fill).
[Journal]
Storage=$(conf_get "$CONF" JOURNAL_STORAGE volatile)
RuntimeMaxUse=$(conf_get "$CONF" JOURNAL_MAX 64M)
EOF
  if [ "$(conf_get "$CONF" HW_WATCHDOG on)" = on ]; then
    do_text /etc/systemd/system.conf.d/10-seastones-watchdog.conf 0644 root:root <<EOF
# $MARK: watchdog layer 3. systemd pets /dev/watchdog; a hung kernel is reset by hardware.
[Manager]
RuntimeWatchdogSec=$(conf_get "$CONF" RUNTIME_WATCHDOG_SEC 60)
RebootWatchdogSec=$(conf_get "$CONF" REBOOT_WATCHDOG_SEC 120)
EOF
  fi
  do_text /etc/systemd/logind.conf.d/10-seastones.conf 0644 root:root <<EOF
# $MARK: one press of the power button is a clean shutdown
# (docs/OPERATIONS.md, "Stop it"): rigd ramps to silence on SIGTERM, then the box powers off.
[Login]
HandlePowerKey=poweroff
HandlePowerKeyLongPress=ignore
EOF
  sed -e "s|/data/|$DATA/|g" -e "s|^\( *size \).*|\1${LOG_KB}k|" -e "s|^\( *rotate \).*|\1$LOG_KEEP|" \
      "$REPO/deploy/logrotate/seastones" | do_text /etc/logrotate.d/seastones 0644 root:root
  do_file "$REPO/deploy/nftables/seastones.nft" /etc/nftables.d/seastones.nft 0644 root:root
  do_line /etc/nftables.conf 'include "/etc/nftables.d/seastones.nft"'

  say "the display: autologin -> startx -> .xinitrc loop -> kiosk.sh"
  do_text "/etc/systemd/system/getty@tty1.service.d/autologin.conf" 0644 root:root <<EOF
# $MARK: the kiosk user logs in on the console by itself.
[Service]
ExecStart=
ExecStart=-/sbin/agetty --autologin $KIOSK_USER --noclear %I \$TERM
EOF
  do_text "/home/$KIOSK_USER/.xinitrc" 0755 "$KIOSK_USER:$KIOSK_USER" <<EOF
#!/bin/sh
# $MARK. The display's whole supervision chain: the browser
# exits or is closed by the watchdog -> back in about 3 s.
openbox-session &
while true; do
  SX_DEST=$DEST SX_DATA=$DATA $DEST/deploy/kiosk.sh >> $DATA/log/kiosk.log 2>&1
  echo "\$(date '+%Y-%m-%dT%H:%M:%S') kiosk exited, restarting" >> $DATA/log/kiosk.log
  sleep 3
done
EOF
  do_text "/home/$KIOSK_USER/.bash_profile" 0644 "$KIOSK_USER:$KIOSK_USER" <<EOF
# $MARK. Start the exhibit on the console login, and only there.
if [ -z "\$DISPLAY" ] && [ "\$(tty)" = /dev/tty1 ]; then exec startx > $DATA/log/startx.log 2>&1; fi
EOF

  say "enabling"
  do_run systemctl daemon-reload
  do_run systemctl set-default multi-user.target
  do_run systemctl enable getty@tty1.service nftables.service seastones-station.target \
    seastones-rigd.service seastones-web.service seastones-playable.service \
    seastones-watchdog.timer seastones-reset.timer
  do_run nft -f /etc/nftables.conf
  do_run systemctl restart seastones-station.target
else
  say "launchd agents (the kiosk user's login session)"
  A=/Library/LaunchAgents
  for j in rigd web kiosk watchdog reset playable; do
    src="$REPO/deploy/launchd/local.seastones.$j.plist"
    tmp="$(mktemp "${TMPDIR:-/tmp}/sx-plist.XXXXXX")"
    sub "$src" > "$tmp"
    if [ "$j" = reset ]; then
      h="${RESET_TIME%%:*}"; m="${RESET_TIME##*:}"
      awk -v h="$((10#$h))" -v m="$((10#$m))" '
        /<key>Hour<\/key>/ {print; getline; sub(/<integer>[0-9]+</, "<integer>" h "<"); print; next}
        /<key>Minute<\/key>/ {print; getline; sub(/<integer>[0-9]+</, "<integer>" m "<"); print; next}
        {print}' "$tmp" > "$tmp.2" && mv "$tmp.2" "$tmp"
    fi
    if command -v plutil >/dev/null 2>&1 && ! plutil -lint -s "$tmp"; then
      rm -f "$tmp"; die "generated $j plist does not lint"
    fi
    do_file "$tmp" "$A/local.seastones.$j.plist" 0644 root:wheel
    rm -f "$tmp"
  done
  if live; then
    uid="$(id -u "$KIOSK_USER")"
    if launchctl print "gui/$uid" >/dev/null 2>&1; then
      for j in rigd web kiosk watchdog reset playable; do
        launchctl bootout "gui/$uid/local.seastones.$j" 2>/dev/null || true
        do_run launchctl bootstrap "gui/$uid" "$A/local.seastones.$j.plist"
      done
    else
      note "$KIOSK_USER is not logged in: the agents start at that user's next login"
    fi
  fi
fi

# --- 5. files from an earlier install that this one no longer has ------------------------------
if [ "$PRINT_PATHS" = 0 ]; then
  echo "$MANIFEST" >> "$MANIFEST_NEW"
  LC_ALL=C sort -u "$MANIFEST_NEW" -o "$MANIFEST_NEW"
  if [ -f "$(R "$MANIFEST")" ]; then
    for old in $(LC_ALL=C comm -23 <(LC_ALL=C sort -u "$(R "$MANIFEST")") "$MANIFEST_NEW"); do
      do_remove "$old"
    done
  fi
  NO_MANIFEST=1 do_file "$MANIFEST_NEW" "$MANIFEST" 0644 "$OWN"
fi

# --- 6. what no script can do --------------------------------------------------------------
if [ "$PRINT_PATHS" = 0 ]; then
  say "by hand, once (docs/OPERATIONS.md, 'Setting up')"
  if [ "$PLATFORM" = linux ]; then
    note "1. BIOS: 'Restore on AC power loss' = Power On. Without it the exhibit stays dark after"
    note "   every power cut."
    note "2. Pull the plug at the wall and watch: does the monitor come back by itself?"
    note "3. The audio interface's ALSA name, if it is not hw:0,0: /etc/default/seastones-rigd"
    note "   RIGD_ARGS=\"... --device hw:1,0 ...\" (see deploy/systemd/seastones-rigd.service)."
  else
    note "1. System Settings > Users & Groups > Automatic login: $KIOSK_USER (FileVault must be off)."
    note "2. System Settings > Energy: 'Start up automatically after a power failure'; never sleep."
    note "3. Chrome or Chromium in /Applications."
  fi
  note "Then: set the staff PIN, power-cycle, and time it: $DATA/log/boot.jsonl gets each boot."
fi
finish install
