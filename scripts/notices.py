#!/usr/bin/env python3
"""Generate THIRD-PARTY-NOTICES from the vendored files themselves (CT-12; GAT-04, RIGHTS-7).

    python3 scripts/notices.py            write THIRD-PARTY-NOTICES at the repo root
    python3 scripts/notices.py --check    exit 1 if the committed file is out of date
    make notices                          the same as the first

Every licence text in the output is copied from a file in this repo, never typed in:

* **open-simh / SIMH**: the permission notice is read from the header of each vendored file
  under src/engine/simh/ (they must all carry the same notice; any that differs, or that
  mentions the GPL, stops the generator), with each file's own copyright line, and the tag
  and commit from src/engine/simh/PROVENANCE.md.
* **miniaudio**: src/host/vendor/miniaudio/LICENSE, checked against the SHA-256 in its
  PROVENANCE.md.
* **typefaces**: licenses/<licence>-<family>.txt, each the family's upstream licence file
  with its copyright line (licenses/SOURCES.md says where each came from and its hash), for
  every .woff2 under src/web/assets/fonts/.

Things that are not vendored (the Python packages rigd needs on the station, the platform)
are listed with their licence as named upstream and marked UNVERIFIED: the authority on the
station is the Debian package's /usr/share/doc/<package>/copyright. Techniques taken from the
literature (no code copied) are credited in their own section; their citations are marked
UNVERIFIED until someone checks them against the papers. A "for review" section carries what a
person (Doug, counsel) must decide. The output has no dates, so it is reproducible.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD-PARTY-NOTICES"
SIMH = ROOT / "src" / "engine" / "simh"
MINIAUDIO = ROOT / "src" / "host" / "vendor" / "miniaudio"
FONTS = ROOT / "src" / "web" / "assets" / "fonts"
LICENSES = ROOT / "licenses"
GPL = re.compile(
    r"\bGNU (?:Lesser |Library |Affero )?General Public License\b|\b[AL]?GPL(?:v?\d)?\b"
)

# Each self-hosted face: (file, family, licence file under licenses/, licence name).
# The licence is the one in the font's own name table (nameID 14), checked by
# tests/deploy/test_notices.py when fontTools is installed.
FONT_TABLE = (
    ("roboto-slab-800.woff2", "Roboto Slab", "Apache-2.0-roboto-slab.txt", "Apache License 2.0"),
    ("oswald.woff2", "Oswald", "OFL-1.1-oswald.txt", "SIL Open Font License 1.1"),
    (
        "ibm-plex-sans.woff2",
        "IBM Plex Sans",
        "OFL-1.1-ibm-plex-sans.txt",
        "SIL Open Font License 1.1",
    ),  # fmt: skip
    (
        "jetbrains-mono.woff2",
        "JetBrains Mono",
        "OFL-1.1-jetbrains-mono.txt",
        "SIL Open Font License 1.1",
    ),  # fmt: skip
)

NOT_VENDORED = (
    ("websockets", "python3-websockets", "BSD-3-Clause", "rigd's WebSocket server (protocol v1)"),
    ("cffi", "python3-cffi", "MIT", "rigd's binding to libsxhost"),
    ("pycparser", "python3-pycparser", "BSD-3-Clause", "used by cffi"),
)

LITERATURE = (
    ("minBLEP band-limited steps (the VCO's anti-aliasing, ADR-010)",
     'E. Brandt, "Hard Sync Without Aliasing", Proc. ICMC 2001. Kernels generated by our own '
     "tools/dsp/gen-minblep.py; no third-party code or table is copied."),
    ("minBLAMP band-limited ramps (ADR-010)",
     'F. Esqueda, V. Valimaki, S. Bilbao, "Rounding Corners with BLAMP", Proc. DAFx 2016. '
     "Our own implementation."),
    ("Zero-delay-feedback ladder and state-variable filters (src/engine/dsp/vcf.c)",
     'V. Zavalishin, "The Art of VA Filter Design" (Native Instruments, 2012-2018). Our own '
     "implementation."),
    ("Feedback delay network reverb with a Hadamard matrix (src/engine/dsp/mods.c)",
     "J.-M. Jot and A. Chaigne, \"Digital delay networks for designing artificial reverberators\", "
     "AES 90th Convention, 1991. Our own implementation."),
)  # fmt: skip


class NoticeError(RuntimeError):
    pass


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT)) if p.is_relative_to(ROOT) else str(p)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def simh_notices() -> tuple[list[tuple[str, list[str]]], list[tuple[str, str]]]:
    """The SIMH permission notice(s) in the vendored headers, each with the files carrying it
    (upstream wraps it differently, and sim_fio.h has its own typo, "not be be used", so
    every distinct wording is reproduced as it is), and each file's copyright line."""
    files = sorted(p for p in SIMH.rglob("*") if p.suffix in (".c", ".h"))
    if not files:
        raise NoticeError("no vendored SIMH files under src/engine/simh")
    variants: dict[str, tuple[str, list[str]]] = {}
    rights = []
    for p in files:
        head = p.read_text(encoding="latin-1")[:6000]
        m = re.search(r"(Permission is hereby granted.*?from Robert M Supnik\.)", head, re.S)
        c = re.search(r"Copyright \(c\) [^\n]*", head)
        if not m or not c:
            raise NoticeError(f"{rel(p)}: no SIMH permission notice in its header")
        if GPL.search(head):
            raise NoticeError(f"{rel(p)}: mentions the GPL; tell counsel")
        # the comment's indentation goes; every character of the text stays
        text = "\n".join(ln.strip() for ln in m.group(1).splitlines())
        words = " ".join(text.split())
        if "Permission is hereby granted, free of charge" not in words or "AS IS" not in words:
            raise NoticeError(f"{rel(p)}: not the SIMH permissive notice")
        variants.setdefault(words, (text, []))[1].append(str(p.relative_to(SIMH)))
        rights.append((str(p.relative_to(SIMH)), c.group(0).strip()))
    return list(variants.values()), rights


def provenance_field(path: Path, name: str) -> str:
    m = re.search(rf"^\| {re.escape(name)} \| (.+?) \|$", path.read_text(), re.M)
    if not m:
        raise NoticeError(f"{path.relative_to(ROOT)}: no '{name}' row")
    return m.group(1).strip().strip("`")


def generate() -> str:
    out: list[str] = []
    w = out.append
    w("THIRD-PARTY NOTICES: The 1974 Seastones Rig station software")
    w("=" * 62)
    w("")
    w("Generated by scripts/notices.py from the vendored files in this repository; do not edit")
    w("by hand (regenerate with `make notices`). Every licence text below is copied from a file")
    w("in the repository. Items marked UNVERIFIED were not checked against a vendored file and")
    w("need a person to confirm them (see the last section).")
    w("")
    w("Our own code (the engine, rigd, the page, the tools) is MIT-licensed, Copyright (c) 2026")
    w("Nick D., as stated in each file's header. Interdata, Perkin-Elmer, E-mu, ARP, Buchla,")
    w("Fender Rhodes and Grateful Dead are names or trademarks of their respective owners; no")
    w("endorsement by them or by the SIMH authors is implied.")
    w("")

    # --- SIMH
    notices, rights = simh_notices()
    prov = SIMH / "PROVENANCE.md"
    w("-" * 78)
    w("1. open-simh (SIMH): the Interdata 16-bit CPU simulator, compiled into libseastones")
    w("-" * 78)
    w("")
    w("Derived from SIMH by Robert M. Supnik and contributors, from the open-simh project")
    w(f"(https://github.com/open-simh/simh), tag {provenance_field(prov, 'Tag')}, commit")
    w(f"{provenance_field(prov, 'Commit')}. The vendored files are byte-identical to that commit")
    w("(src/engine/simh/PROVENANCE.md); our changes are separate numbered patches applied at")
    w("build time. Licence verified from the headers of these vendored files:")
    w("")
    for f, c in rights:
        w(f"  {f:<22} {c}")
    w("")
    for text, users in notices:
        who = "every file above" if len(notices) == 1 else ", ".join(users)
        for line in textwrap.wrap(f"The permission notice in {who}, as it appears there:", 90):
            w(line)
        w("")
        for line in text.splitlines():
            w("   " + line if line.strip() else "")
        w("")

    # --- miniaudio
    lic = MINIAUDIO / "LICENSE"
    want = provenance_field(MINIAUDIO / "PROVENANCE.md", "`LICENSE` SHA-256")
    if sha256(lic) != want:
        raise NoticeError("src/host/vendor/miniaudio/LICENSE does not match its PROVENANCE hash")
    w("-" * 78)
    w("2. miniaudio, by David Reid: audio device I/O in libsxhost")
    w("-" * 78)
    w("")
    w(
        f"https://github.com/mackron/miniaudio, tag {provenance_field(MINIAUDIO / 'PROVENANCE.md', 'Tag')}."
    )
    w("Public domain (Unlicense) or MIT No Attribution, at the user's choice; neither requires")
    w("this notice, which is kept as a credit. Verified from src/host/vendor/miniaudio/LICENSE")
    w("(SHA-256 matches its PROVENANCE.md), reproduced verbatim:")
    w("")
    for line in lic.read_text().rstrip().splitlines():
        w("   " + line if line else "")
    w("")

    # --- fonts
    w("-" * 78)
    w("3. Typefaces, self-hosted in the page (src/web/assets/fonts/)")
    w("-" * 78)
    w("")
    present = sorted(p.name for p in FONTS.glob("*.woff2"))
    listed = sorted(f for f, *_ in FONT_TABLE)
    if present != listed:
        raise NoticeError(
            f"fonts on disk {present} differ from scripts/notices.py's table {listed}"
        )
    texts: dict[str, list[str]] = {}
    for f, family, licfile, name in FONT_TABLE:
        lp = LICENSES / licfile
        if not lp.exists():
            raise NoticeError(f"licenses/{licfile} is missing (the {family} licence)")
        texts.setdefault(licfile, []).append(family)
        w(f"  {family} ({f}): {name}; licence and copyright from licenses/{licfile}")
    w("")
    for licfile, families in texts.items():
        w(f"--- {', '.join(families)}: licenses/{licfile} (verbatim) ---")
        w("")
        for line in (LICENSES / licfile).read_text(encoding="utf-8").rstrip().splitlines():
            w("   " + line.rstrip() if line.strip() else "")
        w("")

    # --- not vendored
    w("-" * 78)
    w("4. Installed on the station, not vendored here (UNVERIFIED)")
    w("-" * 78)
    w("")
    w("The station installs these from Debian; their licence is named from upstream and the")
    w("package's /usr/share/doc/<package>/copyright on the image is the authority:")
    w("")
    for mod, pkg, spdx, why in NOT_VENDORED:
        w(f"  {mod} ({pkg}): {spdx}; {why}. UNVERIFIED")
    w("  Python 3 (python3): PSF License. UNVERIFIED")
    w("  Chromium (chromium) and the Debian system: their own notices ship in the image")
    w("  (/usr/share/doc/*/copyright). UNVERIFIED")
    w("")
    w("Development and test only, never on the station: Playwright (Apache-2.0), pytest, ruff,")
    w("numpy, fontTools. Not listed further.")
    w("")

    # --- literature
    w("-" * 78)
    w("5. Techniques from the literature (no third-party code copied)")
    w("-" * 78)
    w("")
    for what, ref in LITERATURE:
        w(f"  {what}:")
        for line in textwrap.wrap(ref, 86):
            w("    " + line)
        w("    Citation UNVERIFIED (not yet checked against the paper).")
    w("")

    # --- for review
    w("-" * 78)
    w("6. For review by a person (Doug, counsel; CT-12, HUM-10)")
    w("-" * 78)
    w("")
    for item in review_items():
        for i, line in enumerate(textwrap.wrap(item, 86)):
            w(("  - " if i == 0 else "    ") + line)
    w("")
    return "\n".join(out)


def review_items() -> list[str]:
    items = []
    manifest = (FONTS / "MANIFEST.txt").read_text() if (FONTS / "MANIFEST.txt").exists() else ""
    about = ROOT / "content" / "captions" / "about.md"
    about_text = about.read_text() if about.exists() else ""
    for _f, family, _lic, name in FONT_TABLE:
        if name.startswith("Apache") and (
            "Licence for all four families: SIL Open Font License" in manifest
            or ("Roboto Slab" in about_text and "SIL Open Font License" in about_text)
        ):
            items.append(
                f"{family} is under the {name} (its own name table and Google Fonts' "
                "apache/ folder say so), but src/web/assets/fonts/MANIFEST.txt and the About "
                "page's notices line (content/captions/about.md) say all four faces are OFL. "
                "The About wording needs Doug's correction; the MANIFEST is the UI lane's."
            )
    items.append(
        'IBM Plex Sans has Reserved Font Name "Plex" under the OFL; the page serves a '
        "Latin subset made by Google Fonts. Counsel to confirm a subset served unmodified "
        "from Google Fonts may keep the name."
    )
    items.append(
        "Section 4 (Debian packages) and section 5 (citations) are UNVERIFIED: check them "
        "on the built image and against the papers before the content lock."
    )
    items.append("No GPL or AGPL code was found in the vendored files (scripts/notices.py checks).")
    return items


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="notices.py")
    ap.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-NOTICES is stale")
    ap.add_argument("-o", "--out", type=Path, default=OUT)
    args = ap.parse_args(argv)
    try:
        text = generate() + "\n"
    except NoticeError as exc:
        print(f"notices: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
            print(
                "notices: THIRD-PARTY-NOTICES is out of date; run `make notices`", file=sys.stderr
            )
            return 1
        print("notices: THIRD-PARTY-NOTICES is up to date")
        return 0
    args.out.write_text(text, encoding="utf-8")
    print(
        f"notices: wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
